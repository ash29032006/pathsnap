"""Build RESULTS.md from the CSV/JSON files in results/ (no numbers are typed by hand).
Usage: python src/make_results_md.py
"""
import json
import os

import pandas as pd

from common import ART, RES, ROOT


def md(df, floatfmt=4):
    df = df.copy()
    for c in df.columns:
        if df[c].dtype.kind == "f":
            df[c] = df[c].map(lambda v: f"{v:.{floatfmt}f}")
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    return "\n".join(lines)


def main():
    out = ["# PathSnap results", "",
           "Generated by `src/make_results_md.py` from the files in `results/` and `artifacts/`.", ""]

    eda = json.load(open(os.path.join(RES, "eda", "eda_summary.json")))
    cand = pd.read_csv(os.path.join(RES, "candidate_stats.csv"))
    out += ["## 1. Dataset", ""]
    rows = []
    for p in ("train", "student_test"):
        e = eda[p]; c = cand[cand.partition == p]
        rows.append(dict(partition=p, trips=e["trips"], gps_points=e["total_gps_points"],
                         missing=e["missing_values"], pct_dt_1s=round(e["pct_dt_exactly_1s"], 4),
                         trips_gap_gt5s=e["trips_with_gaps_over_5s"], max_gap_s=e["max_gap_s"],
                         gps_to_road_median_m=round(e["gps_to_road_median_m"], 2),
                         gps_to_road_p95_m=round(e["gps_to_road_p95_m"], 2),
                         candidate_miss_rate=round(1 - (1 - c.candidate_miss_rate).mul(c.n_points).sum() / c.n_points.sum(), 4)))
    out += [md(pd.DataFrame(rows)), "",
            "Plots: `results/eda/plots/`. Folium maps: `results/maps/eda_*.html`. Per-trip inventory: `results/eda/inventory.csv`.", ""]

    comp = pd.read_csv(os.path.join(RES, "model_comparison.csv"))
    out += ["## 2. Model comparison (8 models)", "",
            "CV = 5-fold GroupKFold over the 80 training trips (every 3rd GPS point). Student-test = all points of the 10 student-test trips.",
            "Top-1 = observation-level: highest-scored candidate equals the reference arc. Macro F1 / log loss are on candidate rows (threshold 0.5).",
            "Route continuity = share of consecutive distinct predicted arcs that are directly connected (HMM with default parameters beta=5, w=1).", ""]
    t = comp[["model", "family", "config", "cv_macro_f1", "cv_macro_f1_std", "cv_top1", "test_top1", "test_macro_f1",
              "test_precision", "test_recall", "test_log_loss", "clf_route_continuity", "hmm_top1",
              "hmm_route_continuity", "train_secs", "inference_ms_per_1k_rows"]]
    out += [md(t), "", "Plots: `results/plots/cv_macro_f1.png`, `student_test_comparison.png`, `log_loss.png`, "
            "`inference_time.png`, `accuracy_vs_cost.png`, `cm_<model>.png`, `history_MLP.png`.", ""]

    bp = os.path.join(RES, "best_params.json")
    if os.path.exists(bp):
        b = json.load(open(bp))
        tvu = pd.read_csv(os.path.join(RES, "tuned_vs_untuned.csv"))
        out += ["## 3. Bayesian optimisation (LightGBM, Optuna TPE)", "",
                f"- Objective: {b['objective']}", f"- Trials: {b['n_trials']} (trial 0 = untuned baseline)",
                f"- Search time: {b['search_secs'] / 60:.1f} min", f"- Best CV Top-1: {b['best_cv_top1']:.4f}", "",
                "Best parameters:", "", "```json", json.dumps(b["best_params"], indent=2), "```", "",
                md(tvu), "", "Trials: `results/optuna_trials.csv`. Plots: `results/plots/optuna_history.png`, `optuna_importance.png`.", ""]

    hv = os.path.join(RES, "hmm_vs_classifier.csv")
    if os.path.exists(hv):
        h = json.load(open(os.path.join(ART, "hmm_config.json")))
        out += ["## 4. HMM / Viterbi route reconstruction (student-test)", "",
                f"Decoder parameters tuned on {len(h['tuned_on'])} training trips with out-of-fold probabilities: "
                f"beta = {h['beta']:.3f} m, emission weight = {h['emis_w']:.3f}.", "",
                md(pd.read_csv(hv)), "", "Per trip:", ""]
        r = pd.read_csv(os.path.join(RES, "route_eval_final.csv"))
        out += [md(r[["trip", "n_points", "clf_top1", "hmm_top1", "clf_continuity", "hmm_continuity",
                      "hmm_route_precision", "hmm_route_recall", "hmm_route_f1", "hmm_breaks"]]), "",
                "Maps: `results/maps/pred_student_test_<trip>.html`. Plots: `results/plots/hmm_vs_classifier_per_trip.png`, "
                "`hmm_param_search.png`. Trials: `results/hmm_trials.csv`.", ""]
    with open(os.path.join(ROOT, "RESULTS.md"), "w") as f:
        f.write("\n".join(out))
    print("wrote RESULTS.md")


if __name__ == "__main__":
    main()
